suppressPackageStartupMessages({library(rtracklayer); library(GenomicRanges)})
s <- read.delim("sites_hg19.tsv")
ch <- import.chain("/gpfs/commons/groups/sanjana_lab/Cas13/masld_atlas/data/broadaway_eqtl/hg19ToHg38.over.chain")
gr <- GRanges(s$chr, IRanges(s$position, width=1), strand="+")
gr$idx <- seq_along(gr)
l <- liftOver(gr, ch)
n <- elementNROWS(l)
cat("sites", length(gr), "mapped_1", sum(n==1), "unmapped", sum(n==0), "multi", sum(n>1), "\n")
ul <- unlist(l[n==1])
out <- data.frame(chr19=s$chr[ul$idx], pos19=s$position[ul$idx], chr38=as.character(seqnames(ul)), pos38=start(ul), strand38=as.character(strand(ul)))
cat("minus strand", sum(out$strand38=="-"), " chr changed", sum(out$chr19!=out$chr38), "\n")
write.table(out, "sites_hg19_to_hg38.tsv", sep="\t", quote=FALSE, row.names=FALSE)
