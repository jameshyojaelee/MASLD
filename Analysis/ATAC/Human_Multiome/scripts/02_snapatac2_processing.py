def main():
    args = parse_args()
    args.input_dir = os.path.abspath(args.input_dir)
    args.output_dir = os.path.abspath(args.output_dir)
    args.sample_csv = os.path.abspath(args.sample_csv)

    os.makedirs(args.output_dir, exist_ok=True)
    os.makedirs(os.path.join(args.output_dir, "qc"), exist_ok=True)
    os.makedirs(os.path.join(args.output_dir, "checkpoints"), exist_ok=True)
    os.makedirs(os.path.join(args.output_dir, "cell_type_peak_sets"), exist_ok=True)

    logger = setup_logging(args.output_dir)
    logger.info("=" * 60)
    logger.info("SnapATAC2 scATAC-seq Processing Pipeline")
    logger.info("  GSE244832 Human Liver (combinatorial indexing)")
    logger.info("  SnapATAC2 version: %s", snap.__version__)
    logger.info("=" * 60)
    logger.info("Parameters:")
    for k, v in vars(args).items():
        logger.info("  %-20s = %s", k, v)

    try:
        # Load metadata
        sample_df = load_sample_metadata(args.sample_csv)
        logger.info("Loaded %d donors. Conditions: %s",
                    len(sample_df), sample_df["condition"].value_counts().to_dict())

        donors_info = discover_donors(args.input_dir, sample_df, logger)
        if not donors_info:
            logger.error("No fragment files found in %s", args.input_dir)
            sys.exit(1)
        logger.info("Found %d donors with fragment files", len(donors_info))

        # Step 1: Import, QC, tile matrix, doublet removal (per-donor backed AnnData)
        processed, qc_df, donor_condition_map = step1_import_qc_tile(donors_info, args, logger)
        if not processed:
            logger.error("No donors passed QC. Exiting.")
            sys.exit(1)
        qc_df.to_csv(os.path.join(args.output_dir, "qc", "qc_summary.csv"), index=False)
        total_cells = sum(a.n_obs for _, a in processed)
        logger.info("Total cells after QC + doublet removal: %d across %d donors",
                     total_cells, len(processed))

        # Step 2: Create AnnDataSet (preserves fragment refs for gene activity + peaks)
        dataset = step2_create_dataset(processed, args.output_dir, logger)

        # Step 3: Feature selection + LSI on AnnDataSet
        dataset = step3_feature_selection_lsi(dataset, args, logger)

        # Step 4: Harmony + UMAP + Leiden (converts to in-memory AnnData)
        adata, use_rep = step4_harmony_and_clustering(
            dataset, donor_condition_map, args, logger
        )

        # Checkpoint: save after clustering
        ckpt_path = os.path.join(args.output_dir, "checkpoints", "after_clustering.h5ad")
        logger.info("Saving checkpoint: %s", ckpt_path)
        adata.write(ckpt_path)

        # Step 5: Cell type annotation (uses AnnDataSet for gene activity)
        adata = step5_cell_type_annotation(adata, dataset, logger)

        ckpt_path = os.path.join(args.output_dir, "checkpoints", "after_annotation.h5ad")
        logger.info("Saving checkpoint: %s", ckpt_path)
        adata.write(ckpt_path)

        # Step 6: Peak calling (uses AnnDataSet for fragment access)
        adata, peaks_ok = step6_peak_calling(adata, dataset, args.output_dir, logger)

        # Step 7: Differential accessibility
        if not args.skip_da:
            step7_differential_accessibility(adata, args.output_dir, logger)

        # Close AnnDataSet and per-donor files
        try:
            dataset.close()
        except Exception:
            pass
        for _, ad_obj in processed:
            try:
                ad_obj.close()
            except Exception:
                pass

        # Save final AnnData
        final_path = os.path.join(args.output_dir, "snapatac2_processed.h5ad")
        logger.info("Saving final AnnData: %s", final_path)
        adata.write(final_path)

        # QC plots
        plot_qc(adata, args.output_dir, logger)

        # Summary
        summary = {
            "timestamp": datetime.now().isoformat(),
            "snapatac2_version": snap.__version__,
            "n_donors_input": len(donors_info),
            "n_donors_pass_qc": len([r for r in qc_df.to_dict("records") if r["status"] == "PASS"]),
            "n_cells_total": int(adata.n_obs),
            "n_clusters": int(adata.obs["leiden"].nunique()),
            "cell_types": adata.obs.get("cell_type", pd.Series()).value_counts().to_dict()
                          if "cell_type" in adata.obs.columns else {},
            "parameters": {k: str(v) for k, v in vars(args).items()},
        }
        with open(os.path.join(args.output_dir, "run_summary.json"), "w") as f:
            json.dump(summary, f, indent=2, default=str)

        logger.info("=" * 60)
        logger.info("Pipeline COMPLETE")
        logger.info("  Total cells: %d", adata.n_obs)
        logger.info("  Clusters: %d", adata.obs["leiden"].nunique())
        if "cell_type" in adata.obs.columns:
            logger.info("  Cell types: %d", adata.obs["cell_type"].nunique())
        logger.info("  Output: %s", args.output_dir)
        logger.info("=" * 60)

    except Exception as e:
        logger.error("Pipeline FAILED: %s", str(e), exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()
