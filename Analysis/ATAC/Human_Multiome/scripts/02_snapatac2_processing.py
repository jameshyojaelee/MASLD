#!/usr/bin/env python3
"""
02_snapatac2_processing.py
==========================
Module 2, Step 2: SnapATAC2 scATAC-seq processing for GSE244832 human liver.

GSE244832 uses combinatorial indexing (NOT 10x Chromium). Fragment files are
generated by the custom bowtie2 alignment pipeline (01_align_scatac.sh).

Pipeline:
  1. Import fragments per donor (backed h5ad) + QC + tile matrix + doublet removal
  2. Create AnnDataSet -> feature selection -> spectral embedding (LSI)
  3. Harmony batch correction (external harmonypy)
  4. UMAP + Leiden clustering
  5. Cell type annotation via gene activity scores (canonical liver markers)
  6. Peak calling (MACS3 via AnnDataSet fragment access)
  7. Differential accessibility per cell type (MASLD vs Normal)

API Notes (SnapATAC2 v2.8):
  - import_fragments(file=) creates backed AnnData preserving fragment references
  - filter_cells() for in-place QC on backed AnnData
  - add_tile_matrix() populates .X; must be called before scrublet
  - filter_doublets() for in-place doublet removal
  - AnnDataSet preserves fragment refs for make_gene_matrix and macs3
  - diff_test takes list[str] cell names, NOT boolean masks
  - diff_test returns polars DataFrame
"""

