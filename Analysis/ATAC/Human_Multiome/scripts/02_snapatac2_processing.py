def load_sample_metadata(csv_path: str) -> pd.DataFrame:
    lines = [line for line in open(csv_path) if not line.startswith("#")]
    from io import StringIO
    return pd.read_csv(StringIO("".join(lines)))


def discover_donors(input_dir: str, sample_df: pd.DataFrame, logger):
    """Find fragment files for each donor."""
    donors = []
    for _, row in sample_df.iterrows():
        donor_id = row["donor_id"]
        condition = row.get("condition", "Unknown")
        frag_file = os.path.join(input_dir, f"{donor_id}_fragments.tsv.gz")
        if not os.path.isfile(frag_file):
            frag_file = os.path.join(input_dir, donor_id, "outs", "atac_fragments.tsv.gz")
        if os.path.isfile(frag_file):
            donors.append((donor_id, condition, frag_file))
        else:
            logger.warning("Fragment file missing for %s - skipping", donor_id)
    return donors


def plot_qc(adata, output_dir: str, logger):
    if not HAS_MPL:
        return
    qc_dir = os.path.join(output_dir, "qc")
    os.makedirs(qc_dir, exist_ok=True)

    if "tsse" in adata.obs.columns:
        fig, ax = plt.subplots(figsize=(8, 5))
        ax.hist(adata.obs["tsse"].values, bins=100, edgecolor="black", alpha=0.7)
        ax.axvline(4.0, color="red", linestyle="--", label="TSS >= 4")
        ax.set_xlabel("TSS Enrichment Score")
        ax.set_ylabel("Cells")
        ax.set_title("TSS Enrichment Distribution (post-QC)")
        ax.legend()
        fig.savefig(os.path.join(qc_dir, "tsse_histogram.png"), dpi=150, bbox_inches="tight")
        plt.close(fig)

    if "n_fragment" in adata.obs.columns:
        fig, ax = plt.subplots(figsize=(8, 5))
        ax.hist(np.log10(adata.obs["n_fragment"].values + 1), bins=100, edgecolor="black", alpha=0.7)
        ax.set_xlabel("log10(n_fragments + 1)")
        ax.set_ylabel("Cells")
        ax.set_title("Fragment Count Distribution (post-QC)")
        fig.savefig(os.path.join(qc_dir, "fragment_count_histogram.png"), dpi=150, bbox_inches="tight")
        plt.close(fig)

    if "X_umap" in adata.obsm:
        umap_coords = adata.obsm["X_umap"]
        for color_col, title_suffix in [
            ("donor_id", "donor"), ("condition", "condition"),
            ("leiden", "cluster"), ("cell_type", "cell_type"),
        ]:
            if color_col not in adata.obs.columns:
                continue
            fig, ax = plt.subplots(figsize=(10, 8))
            categories = adata.obs[color_col].astype(str).values
            unique_cats = np.unique(categories)
            cmap = plt.cm.get_cmap("tab20", max(len(unique_cats), 1))
            for idx, cat in enumerate(unique_cats):
                mask = categories == cat
                ax.scatter(umap_coords[mask, 0], umap_coords[mask, 1],
                           s=1, alpha=0.3, label=cat, color=cmap(idx), rasterized=True)
            ax.set_xlabel("UMAP1")
            ax.set_ylabel("UMAP2")
            ax.set_title(f"scATAC UMAP - {title_suffix}")
            if len(unique_cats) <= 20:
                ax.legend(markerscale=5, fontsize=7, bbox_to_anchor=(1.05, 1), loc="upper left")
            fig.savefig(os.path.join(qc_dir, f"umap_{title_suffix}.png"), dpi=150, bbox_inches="tight")
            plt.close(fig)
            logger.info("Saved UMAP plot: %s", title_suffix)


