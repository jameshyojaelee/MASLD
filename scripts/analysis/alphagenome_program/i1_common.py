def load_model(checkpoint_path=CHECKPOINT, fasta_path: str | None = FASTA_PATH):
    """Restore the local checkpoint onto the first GPU.

    Same construction as `h1_runtime_common.load_model`: the packaged
    `default_organism_settings()` points fasta/gtf/splice/calibration at remote Google Storage URLs,
    which are replaced with the project's own audited GRCh38 FASTA and with None for everything
    else, so nothing is fetched at load time. Metadata is left at the packaged default for BOTH
    organisms, which keeps Orbax's strict checkpoint validation on.

    Consequence recorded here rather than discovered later: with `calibration_path=None` the model
    has no calibration scorer, so `score_variant` returns raw scores and no `quantiles` layer. The
    comparison against the archive is therefore raw-against-raw by construction.
    """
    import dataclasses

    import jax
    from alphagenome.models import dna_model as dna_model_api
    from alphagenome_research.model import dna_model

    settings = dict(dna_model.default_organism_settings())
    human = dna_model_api.Organism.HOMO_SAPIENS
    mouse = dna_model_api.Organism.MUS_MUSCULUS
    settings[human] = dataclasses.replace(
        settings[human],
        fasta_path=fasta_path,
        gtf_feather_path=None,
        pas_feather_path=None,
        splice_site_starts_feather_path=None,
        splice_site_ends_feather_path=None,
        calibration_path=None,
    )
    settings[mouse] = dataclasses.replace(
        settings[mouse],
        fasta_path=None,
        gtf_feather_path=None,
        pas_feather_path=None,
        splice_site_starts_feather_path=None,
        splice_site_ends_feather_path=None,
        calibration_path=None,
    )

    device = jax.local_devices()[0]
    if device.platform != "gpu":
        raise ContractError(f"expected a GPU device, jax offers {jax.local_devices()}")
    t0 = time.time()
    model = dna_model.create(str(checkpoint_path), organism_settings=settings, device=device)
    load_s = time.time() - t0
    log(f"checkpoint restored in {load_s:.1f}s onto {device}")
    return model, device, load_s


def gpu_card() -> dict:
    """The card this process is bound to, recorded in every output row (amendment 01 section 3)."""
    import subprocess

    try:
        out = subprocess.run(
            [
                "nvidia-smi",
                "--query-gpu=name,memory.total,driver_version,compute_cap",
                "--format=csv,noheader",
            ],
            capture_output=True,
            text=True,
            timeout=60,
            check=True,
        ).stdout.strip().splitlines()[0]
    except Exception as exc:  # pragma: no cover - platform dependent
        return {"card": "unknown", "error": repr(exc)}
    name, mem, driver, cap = (p.strip() for p in out.split(","))
    tag = "l40s" if "L40S" in name.upper() else ("b6k" if "BLACKWELL" in name.upper() else "other")
    return {
        "card": name,
        "card_tag": tag,
        "card_memory_total": mem,
        "driver_version": driver,
        "compute_capability": cap,
    }


def memory_stats(device) -> dict:
    try:
        st = device.memory_stats() or {}
    except Exception as exc:  # pragma: no cover
        return {"error": repr(exc)}
    return {k: int(v) for k, v in st.items() if isinstance(v, (int, float))}


def atac_dnase_scorers():
    """The two archived Atlas scorers, taken from the SDK's own recommended dict, not re-specified.

    Returned for their settings only. Their width and aggregation are asserted here so that a later
    SDK that changed either would stop this arm rather than quietly redefine the gate's quantity.
    """
    from alphagenome.models import variant_scorers

    atac = variant_scorers.RECOMMENDED_VARIANT_SCORERS["ATAC"]
    dnase = variant_scorers.RECOMMENDED_VARIANT_SCORERS["DNASE"]
    for s, want in ((atac, "ATAC"), (dnase, "DNASE")):
        if int(s.width) != CENTER_MASK_WIDTH:
            raise ContractError(f"{want} scorer width is {s.width}, expected {CENTER_MASK_WIDTH}")
        if s.aggregation_type.name != "DIFF_LOG2_SUM":
            raise ContractError(f"{want} aggregation is {s.aggregation_type}, expected DIFF_LOG2_SUM")
    return atac, dnase


def center_mask_and_aggregation():
    """The packaged centre-mask builder and aggregation, imported rather than re-implemented.

    `model.score_variant` cannot be used in this offline setup: `_predict_variant` unconditionally
    calls `jnp.asarray(splice_junction_masks.splice_sites)`, and `splice_sites` is None whenever the
    model is built without a splice-site extractor, which is how it is built here because the
    packaged extractor's feather files live behind a Google Storage URL and compute nodes have no
    egress. Requesting a splice annotation in order to score an ATAC track would also change which
    annotation vintage enters the run.

    So the two `predict_sequence` calls the runtime probe already validated are used instead, and the
    Atlas readout is applied with the SAME functions `score_variant` would have applied:
    `create_center_mask` for the mask and `_apply_aggregation` for DIFF_LOG2_SUM. For a matched-
    reference SNV the two routes see identical inputs: `extract_variant_sequences` inserts
    `variant.reference_bases` into the reference window, which is a no-op when the genome base already
    equals REF (checked for every variant), and it inserts the single ALT base for the alternate;
    indel stitching does not apply to a substitution, splice-junction post-processing touches only
    the SPLICE_JUNCTIONS head, and the interval is on the positive strand so strand handling is a
    no-op. What differs is only which track columns are returned, which does not change a value.
    """
    from alphagenome.models import variant_scorers
    from alphagenome_research.model.variant_scoring import center_mask as cm
    from alphagenome_research.model.variant_scoring import variant_scoring as vs

    return cm.create_center_mask, cm._apply_aggregation, variant_scorers.AggregationType, vs.get_resolution


