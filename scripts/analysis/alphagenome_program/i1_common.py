"""Shared helpers for the AD.1 gate and the zero-shot local caQTL endpoint.

AD.1 asks whether the LOCAL `google/alphagenome-all-folds` weights reproduce the ARCHIVED hosted
AlphaGenome *Atlas* accessibility ranking on the 3,845 matched Currin caQTL peak leads at
Spearman >= 0.9. That means the local score has to be the same quantity the Atlas column is.

The archived column `alphagenome_atac_liver` is built in
`scripts/analysis/alphagenome_program/c1_matched_endogenous.py:load_atlas_chunks()` as the mean of
the RAW `.X` value over the three liver ATAC tracks of the hosted Atlas `ATAC` scorer. In SDK 0.9.0
that scorer is

    RECOMMENDED_VARIANT_SCORERS['ATAC'] = CenterMaskScorer(
        requested_output=ATAC, width=501, aggregation_type=DIFF_LOG2_SUM)

i.e. log2(1 + sum_alt over a 501-bp variant-centred mask) - log2(1 + sum_ref over the same mask),
per track. DNASE is the same scorer at the same width, averaged over its two liver tracks.

So the local side uses the PACKAGED scorer through `model.score_variant`, not the hand-rolled
+/-2 kb mean-|track| readout of `h1_anchor_hsd17b13.py`. That readout answers a different question
(the hosted model API's indel recipe) and would not be comparable with an Atlas column.
The archived `*_quantile` layer is NOT used: the local runtime ships no calibration table, returns a
predicted track rather than a calibrated quantile, and the runtime probe already recorded that Atlas
quantiles must not be pooled with local values. Raw is compared with raw.

Guards this module enforces, from ADAPTATION_ARM_AMENDMENT_01.md:
  - section 3: every score is produced on ONE card, the card is recorded in every row, and a
    mixed-card table is rescored rather than merged.
  - section 4: the packaged one-hot encoder writes a zero vector for any byte that is not A/C/G/T
    and warns about nothing, so every extracted window is alphabet-validated here before it is
    scored, and every rejected window is counted and reported.

Statistics are the C-package recipe: 1-Mb blocks as the resampling unit, bootstrap seed 20260914,
`fast_spearman` / `fisher_macro` / within-fold block resampling copied verbatim in behaviour from
`c2_03_fit_heads.py` so the comparator this arm is paired against is regenerated by this loader
rather than transcribed.
"""

