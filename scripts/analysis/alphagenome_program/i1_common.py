def window_bounds(pos1: int, length: int) -> tuple[int, int]:
    """Variant-centred window. The variant's 0-based offset is exactly length // 2."""
    start0 = pos1 - 1 - length // 2
    return start0, start0 + length


def extract_ref_alt(fasta, chrom: str, start0: int, end: int, pos1: int, ref: str, alt: str):
    """The REF and ALT windows for a substitution, uppercased, same length.

    Equivalent to `alphagenome_research.io.genome.extract_variant_sequences` for a same-length
    substitution: the extended_length term is zero, `insert_reference_variant` writes REF over a base
    that already equals REF, and `insert_alternate_variant` writes ALT in its place. The SDK's own
    extractor opens the FASTA with `sequence_always_upper=True`, so uppercasing here matches it.
    """
    width = end - start0
    seq = fasta.fetch(chrom, start0, end).upper()
    if len(seq) != width:
        raise ContractError(f"fasta returned {len(seq)} bp for {chrom}:{start0}-{end}, wanted {width}")
    i = pos1 - 1 - start0
    if seq[i : i + len(ref)] != ref.upper():
        raise ContractError(
            f"reference mismatch at {chrom}:{pos1}: window has {seq[i:i+len(ref)]}, label says {ref}"
        )
    alt_seq = seq[:i] + alt.upper() + seq[i + len(ref) :]
    if len(alt_seq) != width:
        raise ContractError(f"alt window is {len(alt_seq)} bp, wanted {width}")
    if sum(1 for a, b in zip(seq, alt_seq) if a != b) != 1:
        raise ContractError(f"ref and alt windows differ at more than one position at {chrom}:{pos1}")
    return seq, alt_seq


def validate_window(fasta, chrom: str, start0: int, end: int, pos1: int, ref: str) -> dict:
    """Reject any window the packaged encoder would silently zero-vector.

    `alphagenome.io.fasta.FastaExtractor` opens the FASTA with `sequence_always_upper=True`, so
    soft-masked repeats are not the hazard; two other things are. It pads an out-of-bounds interval
    with literal 'N', and a real assembly gap inside the window is 'N' in the FASTA itself. Both
    become zero vectors with no warning, so both are checked here on the same interval the model
    will extract, and a window that fails is not scored and not silently replaced.
    """
    chrom_len = fasta.get_reference_length(chrom)
    rec = {
        "window_start0": start0,
        "window_end": end,
        "chrom_length": chrom_len,
        "out_of_bounds": bool(start0 < 0 or end > chrom_len),
    }
    lo, hi = max(0, start0), min(chrom_len, end)
    seq = fasta.fetch(chrom, lo, hi).upper()
    bad = {}
    for ch in set(seq):
        if ch not in ACGT:
            bad[ch] = seq.count(ch)
    rec["n_non_acgt"] = int(sum(bad.values())) + (end - start0) - len(seq)
    rec["non_acgt_characters"] = bad
    observed = seq[pos1 - 1 - lo] if lo <= pos1 - 1 < hi else ""
    rec["reference_base"] = observed
    rec["reference_match"] = bool(observed == str(ref).upper()[0])
    rec["acgt_ok"] = bool(rec["n_non_acgt"] == 0 and not rec["out_of_bounds"])
    return rec


