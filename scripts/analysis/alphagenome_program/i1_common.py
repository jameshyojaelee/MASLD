# statistics, behaviour copied from c2_03_fit_heads.py so the comparator is regenerated not quoted
# ------------------------------------------------------------------------------------------------
def fast_spearman(observed: np.ndarray, predicted: np.ndarray) -> float:
    from scipy.stats import rankdata

    observed = np.asarray(observed, dtype=np.float64)
    predicted = np.asarray(predicted, dtype=np.float64)
    if observed.size < 3 or np.all(predicted == predicted[0]) or np.all(observed == observed[0]):
        return float("nan")
    left = rankdata(observed)
    right = rankdata(predicted)
    left = left - left.mean()
    right = right - right.mean()
    denominator = float(np.sqrt(np.sum(left**2) * np.sum(right**2)))
    return float("nan") if denominator == 0 else float(np.sum(left * right) / denominator)


def fisher_macro(values) -> float:
    array = np.asarray(values, dtype=np.float64)
    if not np.isfinite(array).all():
        return float("nan")
    clipped = np.clip(array, -0.999999, 0.999999)
    return float(np.tanh(np.mean(np.arctanh(clipped))))


def macro_over_folds(observed: np.ndarray, predicted: np.ndarray, folds: np.ndarray, n_folds=5) -> float:
    return fisher_macro(
        [fast_spearman(observed[folds == f], predicted[folds == f]) for f in range(n_folds)]
    )


def interval_of(samples: np.ndarray) -> tuple[float, float, float]:
    valid = samples[np.isfinite(samples)]
    if valid.size < int(0.95 * samples.size):
        return float("nan"), float("nan"), float("nan")
    low, high = (float(v) for v in np.quantile(valid, (0.025, 0.975)))
    return low, high, float(np.std(valid, ddof=1))


def bootstrap_p(diff_samples: np.ndarray) -> tuple[float, str]:
    d = diff_samples[np.isfinite(diff_samples)]
    if d.size == 0:
        return float("nan"), "no_valid_draws"
    p = 2.0 * min(float((d <= 0).mean()), float((d >= 0).mean()))
    p = min(1.0, p)
    floor = 1.0 / d.size
    if p < floor:
        return floor, f"floored_at_1/{d.size}_draws"
    return float(p), ""


def block_bootstrap_plain(
    observed: np.ndarray,
    arms: dict,
    blocks: np.ndarray,
    *,
    resamples: int = RESAMPLES,
    seed: int = BOOTSTRAP_SEED,
) -> dict:
    """Resample 1-Mb blocks with replacement; every arm recomputed inside the SAME draw.

    Used for the AD.1 gate correlation, which has no fold structure: the gate compares two score
    sets to each other, and the resampling unit is still the 1-Mb block.
    """
    unique = np.array(sorted(set(blocks.tolist())))
    lookup = {b: np.flatnonzero(blocks == b) for b in unique}
    rng = np.random.default_rng(seed)
    out = {name: np.full(resamples, np.nan) for name in arms}
    for it in range(resamples):
        sampled = rng.integers(0, unique.size, size=unique.size)
        idx = np.concatenate([lookup[unique[j]] for j in sampled])
        obs = observed[idx]
        for name, values in arms.items():
            out[name][it] = fast_spearman(obs, values[idx])
    return out


def block_bootstrap_within_fold(
    observed: np.ndarray,
    arms: dict,
    folds: np.ndarray,
    blocks: np.ndarray,
    *,
    resamples: int = RESAMPLES,
    seed: int = BOOTSTRAP_SEED,
    n_folds: int = 5,
) -> tuple[dict, dict]:
    """Identical in behaviour to `c2_03_fit_heads.block_bootstrap`.

    Blocks are resampled WITHIN each held-out fold, every arm is recomputed inside the same draw
    (so arm differences are paired), the macro is the Fisher-z average over folds and the pooled
    statistic is the single Spearman over the concatenated draw.
    """
    by_fold = {}
    empty = []
    for fold in range(n_folds):
        rows = np.flatnonzero(folds == fold)
        unique = sorted(set(blocks[rows].tolist()))
        if not unique:
            empty.append(fold)
        by_fold[fold] = (unique, {b: rows[blocks[rows] == b] for b in unique})
    if empty:
        # A Fisher-z macro over folds is undefined if a fold contributes nothing, and resampling an
        # empty fold fails inside numpy with an error that names neither the fold nor the cause.
        raise ContractError(
            f"held-out fold(s) {empty} carry no variants, so a 5-fold macro cannot be formed; "
            f"fold sizes are {[int((folds == f).sum()) for f in range(n_folds)]}"
        )
    rng = np.random.default_rng(seed)
    macro = {name: np.full(resamples, np.nan) for name in arms}
    pooled = {name: np.full(resamples, np.nan) for name in arms}
    names = list(arms)
    for it in range(resamples):
        per_fold = []
        for fold in range(n_folds):
            unique, lookup = by_fold[fold]
            sampled = rng.integers(0, len(unique), size=len(unique))
            per_fold.append(np.concatenate([lookup[unique[j]] for j in sampled]))
        all_idx = np.concatenate(per_fold)
        fold_obs = [observed[i] for i in per_fold]
        pooled_obs = observed[all_idx]
        for name in names:
            v = arms[name]
            macro[name][it] = fisher_macro(
                [fast_spearman(fold_obs[f], v[per_fold[f]]) for f in range(n_folds)]
            )
            pooled[name][it] = fast_spearman(pooled_obs, v[all_idx])
    return macro, pooled
